import fs from 'fs';
import path from 'path';

const root = process.cwd();
const schemaPath = path.join(root, 'schema.json');
const outPath = path.join(root, 'reports', 'schema-create-fields.json');

const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));

function isAutoGenerated(column) {
  return Boolean(column.default && typeof column.default === 'string' && column.default.includes('nextval('));
}

function shouldShowInCreateForm(column) {
  return !(column.default && isAutoGenerated(column));
}

const report = { generated_at: new Date().toISOString(), tables: {} };
for (const table of schema) {
  const cols = table.columns.map(c => c.column);
  const shown = table.columns.filter(c => shouldShowInCreateForm(c)).map(c => c.column);
  const hidden = table.columns.filter(c => !shouldShowInCreateForm(c)).map(c => c.column);
  report.tables[table.table_name] = { column_count: cols.length, columns: cols, create_shown: shown, create_hidden: hidden };
}

fs.writeFileSync(outPath, JSON.stringify(report, null, 2), 'utf8');
console.log('Wrote', outPath);
