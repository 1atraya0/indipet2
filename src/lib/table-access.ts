function getTable(tableName: string): TableDefinition {
  const table = tableLookup[tableName];
  if (!table) {
    throw new Error(`Unknown table: ${tableName}`);
  }

  return table;
}

function normalizeValue(column: ColumnDefinition, value: unknown) {
  if (value === undefined) {
    return undefined;
  }

  if (value === null || value === "") {
    return null;
  }

  const kind = getFieldKind(column);

  if (kind === "checkbox") {
    if (typeof value === "boolean") return value;
    if (typeof value === "string") return ["true", "1", "on", "yes"].includes(value.toLowerCase());
    return Boolean(value);
  }

  if (kind === "number") {
    if (typeof value === "number") return value;
    const parsed = Number(value);
    return Number.isNaN(parsed) ? null : parsed;
  }

  if (kind === "json") {
    if (typeof value === "string") {
      try {
        return JSON.parse(value);
      } catch {
        return null;
      }
    }
    return value;
  }

  if (kind === "date" || kind === "time" || kind === "datetime") {
    return String(value);
  }

  return String(value);
}

function normalizeRecordInput(table: TableDefinition, input: RecordPayload) {
  const normalized: Record<string, unknown> = {};

  for (const column of table.columns) {
    if (!(column.column in input)) continue;
    const value = normalizeValue(column, input[column.column]);
    if (value !== undefined) {
      normalized[column.column] = value;
    }
  }

  return normalized;
}

function getOrderColumn(table: TableDefinition) {
  return getPrimaryKey(table) ?? table.columns[0]?.column ?? "";
}

function decorateEmployeeCode(table: TableDefinition, row: Record<string, unknown>) {
  if (table.table_name !== "employee_master") {
    return row;
  }

  return {
    ...row,
    employee_code: formatEmployeeCode(row),
  };
}

function buildWhereClause(table: TableDefinition, recordId: string, paramOffset = 0) {
  const primaryKey = getPrimaryKey(table);
  if (!primaryKey) {
    throw new Error(`Table ${table.table_name} does not have a primary key`);
  }

  const pkColumn = table.columns.find((column) => column.column === primaryKey);
  const value = normalizeValue(pkColumn ?? table.columns[0], recordId);

  return {
    where: `${quoteIdentifier(primaryKey)} = $${paramOffset + 1}`,
    values: [value],
  };
}

function getInboundForeignKeys(tableName: string) {
  return allTables.flatMap((table) =>
    table.foreign_keys
      .filter((foreignKey) => foreignKey.references_table === tableName)
      .map((foreignKey) => ({ table, foreignKey })),
  );
}

type Queryable = { query: typeof pool.query };

async function resetTableSequence(client: Queryable, tableName: string) {
  const table = getTable(tableName);
  const primaryKey = getPrimaryKey(table);

  if (!primaryKey) {
    return;
  }

  const pkColumn = table.columns.find((column) => column.column === primaryKey);
  if (!pkColumn || !isAutoGenerated(pkColumn)) {
    return;
  }

  const sequenceResult = await client.query<{ sequence_name: string | null }>(
    "select pg_get_serial_sequence($1, $2) as sequence_name",
    [table.table_name, primaryKey],
  );

  const sequenceName = sequenceResult.rows[0]?.sequence_name;
  if (!sequenceName) {
    return;
  }

  await client.query(
    `select setval($1, coalesce((select max(${quoteIdentifier(primaryKey)}) from ${quoteIdentifier(table.table_name)}), 0) + 1, false)`,
    [sequenceName],
  );
}

