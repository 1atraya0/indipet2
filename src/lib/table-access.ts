async function deleteTableRowWithDependents(
  client: Queryable,
  tableName: string,
  recordId: string,
  visited: Set<string>,
  touchedTables: Set<string>,
) {
  const table = getTable(tableName);
  const primaryKey = getPrimaryKey(table);

  if (!primaryKey) {
    throw new Error(`Table ${table.table_name} does not have a primary key`);
  }

  const pkColumn = table.columns.find((column) => column.column === primaryKey);
  const recordValue = normalizeValue(pkColumn ?? table.columns[0], recordId);
  const visitKey = `${table.table_name}:${String(recordValue)}`;

  if (visited.has(visitKey)) {
    return null;
  }

  const currentResult = await client.query(
    `select * from ${quoteIdentifier(table.table_name)} where ${quoteIdentifier(primaryKey)} = $1 limit 1`,
    [recordValue],
  );

  const currentRow = currentResult.rows[0];
  if (!currentRow) {
    return null;
  }

  visited.add(visitKey);
  touchedTables.add(table.table_name);

  for (const { table: childTable, foreignKey } of getInboundForeignKeys(table.table_name)) {
    const childPrimaryKey = getPrimaryKey(childTable);
    if (!childPrimaryKey) {
      continue;
    }

    const referencedValue = currentRow[foreignKey.references_column];
    if (referencedValue === undefined || referencedValue === null || referencedValue === "") {
      continue;
    }

    const childRows = await client.query(
      `select ${quoteIdentifier(childPrimaryKey)} as primary_key from ${quoteIdentifier(childTable.table_name)} where ${quoteIdentifier(foreignKey.column)} = $1`,
      [referencedValue],
    );

    for (const childRow of childRows.rows) {
      await deleteTableRowWithDependents(client, childTable.table_name, String(childRow.primary_key), visited, touchedTables);
    }
  }

  const deleteResult = await client.query(
    `delete from ${quoteIdentifier(table.table_name)} where ${quoteIdentifier(primaryKey)} = $1 returning *`,
    [recordValue],
  );

  return deleteResult.rows[0] ?? currentRow;
}

export async function listTableRows(tableName: string, limit = 25, offset = 0) {
  const table = getTable(tableName);
  const orderColumn = getOrderColumn(table);
  const rowsResult = await pool.query(
    `select * from ${quoteIdentifier(table.table_name)} order by ${quoteIdentifier(orderColumn)} desc limit $1 offset $2`,
    [limit, offset],
  );
  const countResult = await pool.query(`select count(*)::int as count from ${quoteIdentifier(table.table_name)}`);

  return {
    table,
    rows: rowsResult.rows.map((row) => decorateEmployeeCode(table, row)),
    total: Number(countResult.rows[0]?.count ?? 0),
  };
}

