DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM information_schema.table_constraints
    WHERE table_schema = 'public'
      AND table_name = 'employee_address'
      AND constraint_name = 'employee_address_employee_id_fkey'
  ) THEN
    ALTER TABLE employee_address
      ADD CONSTRAINT employee_address_employee_id_fkey
      FOREIGN KEY (employee_id) REFERENCES employee_master(employee_id);
  END IF;
