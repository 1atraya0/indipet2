$$;

CREATE UNIQUE INDEX IF NOT EXISTS employee_address_employee_id_ux
  ON employee_address (employee_id)
  WHERE employee_id IS NOT NULL;

CREATE OR REPLACE FUNCTION sync_employee_address_same_fields()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF COALESCE(NEW.same_address, false) THEN
    NEW.permanent_address_line1 := NEW.present_address_line1;
    NEW.permanent_address_line2 := NEW.present_address_line2;
    NEW.permanent_country := NEW.present_country;
    NEW.permanent_state := NEW.present_state;
    NEW.permanent_city := NEW.present_city;
    NEW.permanent_pincode := NEW.present_pincode;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS employee_address_same_fields_trg ON employee_address;

CREATE TRIGGER employee_address_same_fields_trg
BEFORE INSERT OR UPDATE OF same_address, present_address_line1, present_address_line2, present_country, present_state, present_city, present_pincode
ON employee_address
FOR EACH ROW
EXECUTE FUNCTION sync_employee_address_same_fields();